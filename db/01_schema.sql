-- LibriGest / Biblioteca Ducky - esquema PostgreSQL (21 tablas, diseno S1-S3)
--
-- ADICIONES AL DISENO OFICIAL (solo aditivas y estrictamente necesarias; ver docs/requisitos/matriz_trazabilidad.md, seccion 8):
--   S-1 ejemplar.motivo_baja                    (RF-11: motivo de baja por ejemplar)
--   S-2 libro.tipo_uso admite 'reservado'       (RF-10, D-20)
--   S-3 solicitud_compra 'recibida' + factura_folio/factura_total/fecha_recepcion; detalle_solicitud.cantidad_recibida
--       (RF-06 recepcion y factura; el precio de la ultima compra recibida da el valor de reposicion RN-04)
--   S-4 reporte_generado.tipo ampliado          (RF-16, RF-28; ademas 'indicadores' PS-MET-02/03 e 'errores' PS-S3-06)
--   S-5 indices unicos parciales: prestamo activo por ejemplar; entrada activa de espera por usuario y libro
--   S-6 bitacora.id_usuario admite NULL         (PS-S3-06: un error del sistema puede ocurrir sin sesion; accion 'error_sistema')
--   (Anterior a estas: detalle_solicitud.descripcion, ver mas abajo.)
-- DECISION DE LENGUAJE: los valores de enumeracion (CHECK) los definimos nosotros (el PDF no los fijo), asi que se usan
--   palabras de uso diario: adeudo.estado 'condonado' -> 'cancelado'; reporte_generado.tipo 'deudores' -> 'con_adeudos',
--   'existencia_parcial' -> 'inventario_estante', 'metricas_operativas' -> 'indicadores', 'incidentes' -> 'errores';
--   bitacora.accion 'incidente' -> 'error_sistema', 'adeudo_condonar' -> 'adeudo_cancelar'; intencion 'escalar_bibliotecario'
--   -> 'pasar_a_bibliotecario'; permiso 'design' -> 'diseno'. Los nombres de tablas y columnas del diseno oficial no cambian.
-- No se agregan tablas.
CREATE EXTENSION IF NOT EXISTS unaccent;

-- ===================== S1 =====================
CREATE TABLE permiso (
  id_permiso  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(50)  NOT NULL UNIQUE,
  descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE rol (
  id_rol      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre      VARCHAR(30)  NOT NULL UNIQUE,
  descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE rol_permiso (
  id_rol      INT NOT NULL REFERENCES rol(id_rol) ON DELETE CASCADE,
  id_permiso  INT NOT NULL REFERENCES permiso(id_permiso) ON DELETE CASCADE,
  habilitado  BOOLEAN NOT NULL DEFAULT false,
  PRIMARY KEY (id_rol, id_permiso)
);

CREATE TABLE usuario (
  id_usuario        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  matricula         VARCHAR(10)  NOT NULL UNIQUE,
  nombre_completo   VARCHAR(120) NOT NULL,
  correo            VARCHAR(120) NOT NULL UNIQUE,
  contrasena_hash   VARCHAR(255) NOT NULL,
  id_rol            INT NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
  estado            VARCHAR(20)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo')),
  fuente_validacion VARCHAR(20)  NOT NULL DEFAULT 'manual'
                    CHECK (fuente_validacion IN ('servicios_escolares','recursos_humanos','manual')),
  registro_vigente  BOOLEAN NOT NULL DEFAULT true,
  fecha_alta        DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_baja        DATE NULL
);
CREATE INDEX idx_usuario_id_rol ON usuario(id_rol);

CREATE TABLE bitacora (
  id_bitacora INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Adición al diseño (S-6): NULL para errores sin sesión (errores del servidor o del navegador).
  id_usuario  INT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  accion      VARCHAR(40)  NOT NULL,
  detalle     VARCHAR(200) NOT NULL DEFAULT '',
  fecha       TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_bitacora_id_usuario ON bitacora(id_usuario);

CREATE TABLE recuperacion_contrasena (
  id_token     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario   INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  token        VARCHAR(64) NOT NULL UNIQUE,
  fecha_envio  TIMESTAMP NOT NULL DEFAULT now(),
  fecha_expira TIMESTAMP NOT NULL,
  usado        BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX idx_recuperacion_id_usuario ON recuperacion_contrasena(id_usuario);

CREATE TABLE reporte_generado (
  id_reporte    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario    INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  -- Adición al diseño (S-4): tipos 'con_adeudos','inventario_estante','prestamos_vencidos','prestamos' (RF-16, RF-28),
  -- 'indicadores' (PS-MET-02/03, CTX-03) e 'errores' (PS-S3-06).
  tipo          VARCHAR(20) NOT NULL CHECK (tipo IN ('catalogo_completo','catalogo_activo','usuarios',
                                                     'con_adeudos','inventario_estante','prestamos_vencidos','prestamos',
                                                     'indicadores','errores')),
  formato       VARCHAR(20) NOT NULL DEFAULT 'pantalla' CHECK (formato IN ('pantalla','pdf','impresion')),
  total_titulos SMALLINT NOT NULL DEFAULT 0,
  fecha         TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_reporte_id_usuario ON reporte_generado(id_usuario);

CREATE TABLE solicitud_compra (
  id_solicitud   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio          VARCHAR(10)  NOT NULL UNIQUE,
  id_usuario     INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  justificacion  VARCHAR(200) NOT NULL,
  destinatario   VARCHAR(60)  NOT NULL DEFAULT 'Tesorería',
  fecha          DATE NOT NULL DEFAULT CURRENT_DATE,
  total_estimado DECIMAL(12,2) NOT NULL DEFAULT 0,
  -- Adición al diseño (S-3): estado 'recibida' y datos de factura/recepción (RF-06, RN-04).
  estado         VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','enviada','recibida','cancelada')),
  factura_folio  VARCHAR(30) NULL,
  factura_total  DECIMAL(12,2) NULL,
  fecha_recepcion DATE NULL
);
CREATE INDEX idx_solicitud_id_usuario ON solicitud_compra(id_usuario);

CREATE TABLE ubicacion (
  id_ubicacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  planta       VARCHAR(20) NOT NULL,
  pasillo      CHAR(1)     NOT NULL,
  librero      CHAR(2)     NOT NULL,
  nivel        SMALLINT    NOT NULL
);

CREATE TABLE libro (
  id_libro          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave             VARCHAR(10)  NOT NULL UNIQUE,
  titulo            VARCHAR(200) NOT NULL,
  autor             VARCHAR(120) NOT NULL,
  editorial         VARCHAR(80)  NOT NULL,
  tema              VARCHAR(60)  NOT NULL,
  anio_publicacion  SMALLINT NULL CHECK (anio_publicacion BETWEEN 1000 AND 2100),
  tipo_uso          VARCHAR(20) NOT NULL DEFAULT 'prestamo_externo'
                    -- Adición al diseño (S-2): 'reservado' = libro de bibliografía de cátedra, se consulta en mostrador (RF-10, D-20).
                    CHECK (tipo_uso IN ('prestamo_externo','consulta_interna','reservado')),
  clasificacion     VARCHAR(20)  NOT NULL,
  sinopsis          TEXT NOT NULL,
  precio_referencia DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (precio_referencia >= 0),
  id_ubicacion      INT NOT NULL REFERENCES ubicacion(id_ubicacion) ON DELETE RESTRICT,
  estado            VARCHAR(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo'))
);
CREATE INDEX idx_libro_titulo ON libro(titulo);
CREATE INDEX idx_libro_id_ubicacion ON libro(id_ubicacion);

-- DESVIACION DEL PDF: se agrega `descripcion` (titulo solicitado) porque id_libro es NULL
-- para libros aun no incluidos en el catalogo y el diseno no tiene columna para el titulo.
CREATE TABLE detalle_solicitud (
  id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud    INT NOT NULL REFERENCES solicitud_compra(id_solicitud) ON DELETE CASCADE,
  id_libro        INT NULL REFERENCES libro(id_libro) ON DELETE RESTRICT,
  descripcion     VARCHAR(200) NOT NULL,
  cantidad        SMALLINT NOT NULL CHECK (cantidad BETWEEN 1 AND 10000),
  precio_unitario DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (precio_unitario >= 0),
  -- Adición al diseño (S-3): recepción parcial de la compra (RF-06, D-25).
  cantidad_recibida SMALLINT NOT NULL DEFAULT 0 CHECK (cantidad_recibida >= 0)
);
CREATE INDEX idx_detalle_id_solicitud ON detalle_solicitud(id_solicitud);
CREATE INDEX idx_detalle_id_libro ON detalle_solicitud(id_libro);

CREATE TABLE ejemplar (
  id_ejemplar  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_libro     INT NOT NULL REFERENCES libro(id_libro) ON DELETE RESTRICT,
  numero_copia SMALLINT NOT NULL,
  estado       VARCHAR(20) NOT NULL DEFAULT 'disponible' CHECK (estado IN ('disponible','prestado','baja')),
  fecha_alta   DATE NOT NULL DEFAULT CURRENT_DATE,
  -- Adición al diseño (S-1): motivo de la baja del ejemplar (RF-11, RN-04).
  motivo_baja  VARCHAR(20) NULL CHECK (motivo_baja IN ('perdido','robado','danado','obsoleto')),
  UNIQUE (id_libro, numero_copia)
);

-- ===================== S2 =====================
CREATE TABLE politica_prestamo (
  id_politica      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rol           INT NOT NULL REFERENCES rol(id_rol) ON DELETE RESTRICT,
  dias_prestamo    SMALLINT NOT NULL,
  max_libros       SMALLINT NOT NULL,
  max_renovaciones SMALLINT NOT NULL DEFAULT 0,
  multa_diaria     DECIMAL(8,2) NOT NULL DEFAULT 0,
  vigente_desde    DATE NOT NULL DEFAULT CURRENT_DATE,
  activa           BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX idx_politica_id_rol ON politica_prestamo(id_rol);

CREATE TABLE prestamo (
  id_prestamo       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ejemplar       INT NOT NULL REFERENCES ejemplar(id_ejemplar) ON DELETE RESTRICT,
  id_usuario        INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  id_politica       INT NOT NULL REFERENCES politica_prestamo(id_politica) ON DELETE RESTRICT,
  fecha_prestamo    TIMESTAMP NOT NULL DEFAULT now(),
  fecha_vencimiento DATE NOT NULL,
  fecha_devolucion  TIMESTAMP NULL,
  num_renovaciones  SMALLINT NOT NULL DEFAULT 0,
  estado            VARCHAR(20) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','devuelto','vencido'))
);
CREATE INDEX idx_prestamo_id_ejemplar ON prestamo(id_ejemplar);
CREATE INDEX idx_prestamo_id_usuario ON prestamo(id_usuario);
CREATE INDEX idx_prestamo_id_politica ON prestamo(id_politica);
-- Adición al diseño (S-5): un ejemplar solo puede tener un préstamo abierto (consistencia concurrente, RNF-08).
CREATE UNIQUE INDEX uq_prestamo_ejemplar_abierto ON prestamo(id_ejemplar) WHERE estado IN ('activo','vencido');

CREATE TABLE adeudo (
  id_adeudo    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prestamo  INT NOT NULL REFERENCES prestamo(id_prestamo) ON DELETE RESTRICT,
  tipo         VARCHAR(20) NOT NULL CHECK (tipo IN ('retraso','danio','perdida')),
  dias_retraso SMALLINT NOT NULL DEFAULT 0,
  monto        DECIMAL(10,2) NOT NULL DEFAULT 0,
  estado       VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','pagado','cancelado')),
  fecha_pago   DATE NULL
);
CREATE INDEX idx_adeudo_id_prestamo ON adeudo(id_prestamo);

CREATE TABLE renovacion (
  id_renovacion          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_prestamo            INT NOT NULL REFERENCES prestamo(id_prestamo) ON DELETE RESTRICT,
  fecha                  TIMESTAMP NOT NULL DEFAULT now(),
  nueva_fecha_vencimiento DATE NOT NULL
);
CREATE INDEX idx_renovacion_id_prestamo ON renovacion(id_prestamo);

CREATE TABLE lista_espera (
  id_espera            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario           INT NOT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  id_libro             INT NOT NULL REFERENCES libro(id_libro) ON DELETE RESTRICT,
  fecha_solicitud      TIMESTAMP NOT NULL DEFAULT now(),
  posicion             SMALLINT NOT NULL DEFAULT 1,
  estado               VARCHAR(20) NOT NULL DEFAULT 'en_espera'
                       CHECK (estado IN ('en_espera','notificado','recogido','cancelado')),
  fecha_notificacion   TIMESTAMP NULL,
  fecha_limite_recoger TIMESTAMP NULL
);
CREATE INDEX idx_espera_id_usuario ON lista_espera(id_usuario);
CREATE INDEX idx_espera_id_libro ON lista_espera(id_libro);
-- Adición al diseño (S-5): una entrada activa por usuario y libro (D-19).
CREATE UNIQUE INDEX uq_espera_usuario_libro_activa ON lista_espera(id_usuario, id_libro)
  WHERE estado IN ('en_espera','notificado');

-- ===================== S3 =====================
CREATE TABLE intencion (
  id_intencion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(50)  NOT NULL UNIQUE,
  descripcion  VARCHAR(200) NOT NULL,
  activa       BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE conversacion (
  id_conversacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario      INT NULL REFERENCES usuario(id_usuario) ON DELETE RESTRICT,
  canal           VARCHAR(20) NOT NULL DEFAULT 'web' CHECK (canal IN ('web','movil')),
  fecha_inicio    TIMESTAMP NOT NULL DEFAULT now(),
  fecha_fin       TIMESTAMP NULL,
  resuelta        BOOLEAN NOT NULL DEFAULT false,
  calificacion    SMALLINT NULL CHECK (calificacion BETWEEN 1 AND 5)
);
CREATE INDEX idx_conversacion_id_usuario ON conversacion(id_usuario);

CREATE TABLE mensaje (
  id_mensaje      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_conversacion INT NOT NULL REFERENCES conversacion(id_conversacion) ON DELETE CASCADE,
  id_intencion    INT NULL REFERENCES intencion(id_intencion) ON DELETE RESTRICT,
  emisor          VARCHAR(20) NOT NULL CHECK (emisor IN ('usuario','asistente')),
  texto           TEXT NOT NULL,
  fecha           TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX idx_mensaje_id_conversacion ON mensaje(id_conversacion);
CREATE INDEX idx_mensaje_id_intencion ON mensaje(id_intencion);

CREATE TABLE pregunta_frecuente (
  id_pregunta  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_intencion INT NOT NULL REFERENCES intencion(id_intencion) ON DELETE RESTRICT,
  pregunta     VARCHAR(200) NOT NULL,
  respuesta    TEXT NOT NULL,
  categoria    VARCHAR(40) NOT NULL,
  activa       BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX idx_pregunta_id_intencion ON pregunta_frecuente(id_intencion);
